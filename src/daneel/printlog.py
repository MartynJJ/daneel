"""Print log — an append-only record of every completed print.

Backed by a JSONL file (one JSON object per line): append-safe, human-readable,
and easy to grep or post-process. Defaults to ``~/.local/share/daneel/prints.jsonl``;
override with ``$DANEEL_LOG`` or by passing ``path`` to :class:`PrintLog`.

Logging is manual today (you record a print after it finishes). Phase 4 will
auto-append records from the printer's own telemetry once dispatch lands.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone
from pathlib import Path

from pydantic import BaseModel

STATUSES = ("success", "failed", "aborted", "in_progress")


class PrintRecord(BaseModel):
    """One logged print."""

    id: str
    timestamp: str  # ISO-8601 UTC
    part: str | None = None  # registry part name, if generated by Daneel
    label: str | None = None  # human description ("desk hook v2")
    file: str | None = None  # source model / sliced file
    filament: str | None = None  # e.g. "PLA Basic"
    color: str | None = None
    grams: float | None = None  # filament used
    duration_min: float | None = None  # wall-clock print time
    status: str = "success"
    printer: str = "P1S"
    rating: int | None = None  # subjective 1-5
    notes: str | None = None


def _default_path() -> Path:
    if env := os.environ.get("DANEEL_LOG"):
        return Path(env)
    base = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local" / "share")
    return Path(base) / "daneel" / "prints.jsonl"


class PrintLog:
    """Append-only reader/writer over a JSONL print log."""

    def __init__(self, path: str | Path | None = None) -> None:
        self.path = Path(path or _default_path())

    def records(self) -> list[PrintRecord]:
        """All records in file order. Missing file -> empty list."""
        if not self.path.exists():
            return []
        out: list[PrintRecord] = []
        for line in self.path.read_text().splitlines():
            line = line.strip()
            if line:
                out.append(PrintRecord.model_validate_json(line))
        return out

    def add(self, **fields: object) -> PrintRecord:
        """Append a print. Auto-assigns ``id`` and ``timestamp`` if absent."""
        status = fields.get("status", "success")
        if status not in STATUSES:
            raise ValueError(f"status must be one of {STATUSES}, got {status!r}")
        existing = self.records()
        fields.setdefault("id", f"P{len(existing) + 1:04d}")
        fields.setdefault("timestamp", datetime.now(timezone.utc).isoformat(timespec="seconds"))
        record = PrintRecord.model_validate(fields)

        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.path.open("a") as fh:
            fh.write(record.model_dump_json(exclude_none=True) + "\n")
        return record

    def summary(self) -> dict:
        """Aggregate stats across all records."""
        records = self.records()
        completed = [r for r in records if r.status in ("success", "failed", "aborted")]
        successes = [r for r in records if r.status == "success"]
        by_status: dict[str, int] = {}
        by_part: dict[str, int] = {}
        for r in records:
            by_status[r.status] = by_status.get(r.status, 0) + 1
            key = r.part or r.label or "?"
            by_part[key] = by_part.get(key, 0) + 1
        return {
            "total": len(records),
            "success_rate": (len(successes) / len(completed)) if completed else None,
            "total_grams": sum(r.grams or 0 for r in records),
            "total_hours": sum(r.duration_min or 0 for r in records) / 60,
            "by_status": by_status,
            "by_part": by_part,
        }
